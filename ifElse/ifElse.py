# Pergunte um numero ao usuario e verifique se ele é par ou ímpar.
# numero % 2 == 0 -> par
# numero % 2 != 0 -> impar

# +, -, *, /
# // -> divisao inteira
# % -> resto

numero = float(input('Digite um número: '))

if numero == 0:
    print('O número é neutro!') 

elif numero % 2 == 0:
    print('O número é par!') 

else:
    print('O número é impar!')
    
